import {test,expect} from './consoleTest';
import {readFileSync,mkdirSync} from 'node:fs';
const env=readFileSync(new URL('../../.env',import.meta.url),'utf8');
const key=env.match(/^ADMIN_KEY=(.+)$/m)![1].trim();
test('create endpoint, capture real HTTP, inspect headers and raw body',async({page,request})=>{
 await page.goto('/');
 await page.getByLabel('개발용 관리 키').fill(key);
 await page.getByRole('button',{name:'관리 콘솔 열기'}).click();
 const name='브라우저 검증 '+Date.now();
 await page.getByLabel('엔드포인트 이름').fill(name);
 await page.getByTitle('엔드포인트 생성').click();
 await expect(page.getByRole('button',{name,exact:true})).toBeVisible();
 const url=await page.locator('.url-card code').innerText();
 const response=await request.post(url+'?source=playwright&tag=a&tag=b',{headers:{'Content-Type':'application/json','X-HookScope-Test':'browser'},data:'{ "event": "phase1.verified", "message": "실제 HTTP 요청입니다" }'});
 expect(response.status()).toBe(200);
 await page.getByRole('button',{name:'새로고침'}).click();
 await expect(page.locator('.request')).toHaveCount(1);
 await page.locator('.request').click();
 await expect(page.locator('pre')).toContainText('phase1.verified');
 await page.getByRole('button',{name:'Headers',exact:true}).click();
 await expect(page.locator('.kv-list')).toContainText('browser');
 await page.getByRole('button',{name:'Query',exact:true}).click();
 await expect(page.locator('.kv-list')).toContainText('playwright');
 await page.getByRole('button',{name:'Raw',exact:true}).click();
 await expect(page.locator('pre')).toContainText('{ "event":');
 await page.getByRole('button',{name:'Body',exact:true}).click();
 mkdirSync(new URL('../../docs/screenshots/',import.meta.url),{recursive:true});
 await page.screenshot({path:new URL('../../docs/screenshots/phase1-desktop.png',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:new URL('../../docs/screenshots/phase1-mobile.png',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
});
