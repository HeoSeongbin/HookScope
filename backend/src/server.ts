import {createApp} from './app.js';
import {repository} from './repository.js';
import {pool} from './db.js';
import {createServer} from 'node:http';
import {attachRealtime} from './realtime.js';
import {createTestTransport} from './testSender.js';
import {makeReplayQueue} from './replayQueue.js';
import {createReplayService} from './replayService.js';
import {analyticsRepository} from './analyticsRepository.js';
const key=process.env.ADMIN_KEY??'';
const origin=process.env.FRONTEND_ORIGIN??'http://localhost:5173';
const queue=makeReplayQueue();const replays=createReplayService(repository,key,queue);
const tests=createTestTransport(()=>{const address=server.address();if(!address||typeof address==='string')throw new Error('Server unavailable');return address.port;});
const app=createApp(repository,key,origin,event=>realtime.publish(event),tests,replays,analyticsRepository);
const server=createServer(app);
const realtime=attachRealtime(server,repository,key,origin);
server.listen(Number(process.env.PORT??3000),'0.0.0.0');
server.requestTimeout=15000;server.headersTimeout=10000;
const reconcile=setInterval(()=>{void replays.reconcile().catch(()=>{});},5000);reconcile.unref();
for(const signal of ['SIGTERM','SIGINT']) process.on(signal,()=>{clearInterval(reconcile);void realtime.io.close(()=>{void queue.close().then(()=>pool.end()).then(()=>process.exit(0));});setTimeout(()=>process.exit(1),10000).unref();});
